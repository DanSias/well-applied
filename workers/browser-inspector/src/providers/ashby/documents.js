// The query documents this adapter is allowed to send, pinned (whitespace-collapsed) by SHA-256.
//
// These are the exact documents Ashby's own public job page sends to load an application form, captured from a real page
// (see ../../../test/support/ashby-sanitize-capture.mjs and test/fixtures/ashby/nerdwallet.requests.json). Both are a single
// `query` operation: no mutation, no subscription, no introspection, no directives.
//
// Pinning the whole document, not the operation NAME, is the control: a name proves nothing about what a document does. When
// Ashby changes a document, this file is the ONLY thing that changes (new text, new hash, new fixture); the request
// validator, response validator and mapper do not. The check fails closed: an unknown document is refused, never adapted.
import { createHash } from 'node:crypto';

/** Whitespace-collapsed form: the only normalisation. Comments, aliases, extra fields or operations all change the hash. */
export const normaliseDocument = (query) => query.replace(/\s+/g, ' ').trim();
export const hashDocument = (query) => createHash('sha256').update(normaliseDocument(query)).digest('hex');

